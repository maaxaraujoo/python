frase = "Eu amo comer açai amargo"

print("------------------------------")
print(f"Frase normal: {frase}")
print(f"Quantidade de palavras: {len(frase)} ")
print("------------------------------")
palavra = frase.split()
print(f"Frase com aplicada ao split: {palavra}")
print(f"Quantidade de palavras: {len(palavra)} ")
print("------------------------------")
