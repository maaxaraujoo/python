
numero1 = int(input("Digite o primeiro numero:"))
numero2 = int(input("Digite o segundo numero:"))

print("----Operadores aritmeticos----")
print(f"Numeros digitados {numero1} e {numero2}")
print("Soma:", numero1 + numero2)
print("Subtracao:", numero1 - numero2)
print("Multiplicacao:", numero1 * numero2)
print("Divisao:", numero1 / numero2)
print("Divisao inteira:", numero1 // numero2)
print("Resto:", numero1 % numero2)
print("Potencia:", numero1 ** numero2)
print("-------------------------------")

