# 18.string_capitalize_title.py
frase0 = "eu estudo linguagem de programação"
print("----------------------------------------------------------------------------")
print(f"Frase original:{frase0}")
nova0 = frase0.capitalize()
print(f"Frase original utilizando capitalize:{nova0}")
print("----------------------------------------------------------------------------")
print(f"Frase original:{frase0}")
nova1 = frase0.title()
print(f"Frase original utilizando title:{nova1}")
print("----------------------------------------------------------------------------")
